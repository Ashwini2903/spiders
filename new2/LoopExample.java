class  LoopExample
{
	public static void main(String[] args) 
	{
	    //int i = 10;
			for(int i=1;i<=10;i++)
		{
		    System.out.println(i);
		}

         System.out.println();
		for (char ch = 'A';ch <= 'Z' ; ch++ )
		{
			System.out.println(ch);
		}

		System.out.println();
		for (char ch = 'z';ch <= 'a' ; ch-- )
		{
			System.out.println(ch);
		}
	}
}
